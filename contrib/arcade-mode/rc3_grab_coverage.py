def blocker(entry):
    ns, value = entry["id_namespace"], entry["native_id"]
    if (ns == "Enum.DetailedGrabType" and value == 17) or (ns == "Enum.GrabType" and value == 35):
        return "Original seatbelt BS-shifty sequence 15021 emits Nose BS Shifty detail 24; actual native scoring identity remains unverified. No substitute identity assigned."
    if ns == "Enum.OneFooterType" or (ns == "Enum.GrabType" and value in
            {15, 16, 17, 22, 23, 28, 32, 33, 34, 39, 40, 44, 57}):
        return FOOT_BLOCKER
    if ns == "Enum.FingerflipType" or (ns == "Enum.GrabType" and value >= 61):
        return FINGER_BLOCKER
    if ns == "Enum.GrabType" and 53 <= value <= 56:
        return GROUND_BLOCKER
    return ENTRY_BLOCKER


def build():
    source = json.loads((RESEARCH / "native-grab-source-catalog.json").read_text())
    finger_rows = json.loads((RESEARCH / "native-fingerflip-transitions.json").read_text())["transitions"]
    finger_code = (ROOT / "Extension/ArcadeMode/arcade_fingerflip.h").read_text()
    declarations = re.findall(r"\{(\d+),(\d+),(\d+),(\d+)\}", finger_code)
    assert [tuple(map(int, r)) for r in declarations] == [
        (r["native_id"], r["family"], r["input_bitmap"], r["destination"]) for r in finger_rows]
    finger_actors = re.findall(r"\{(0x[^}]+)\}[^\n]*// \d+ ",
        (ROOT / "Engine/Game/Build/20260929/arcade_fingerflip.h").read_text())
    assert [str(uuid.UUID(bytes_le=bytes(int(b.strip(), 16) for b in raw.split(","))))
            for raw in finger_actors] == [r["actor_guid"] for r in finger_rows]
    family_names = {1: "FS", 2: "BS", 3: "Tail", 4: "Seatbelt", 5: "Crail", 6: "Nose", 7: "Stale", 8: "Weddle", 9: "Double"}
    for finger in finger_rows:
        directions = [name for bit, name in [(2, "neutral or Left"), (4, "Right"), (8, "Down"), (16, "Up")]
                      if finger["input_bitmap"] & bit]
        finger["arcade_binding"] = ("Establish " + family_names[finger["family"]] + " Grab, keep B held, then " +
            " / ".join(directions) + "+X; release B for native exit")
    fingers = {r["native_id"]: r for r in finger_rows}
    ground_contract = (ROOT / "Engine/Game/Build/20260929/arcade_ground_grab.h").read_text()
    ground_rows = re.findall(r"\{(0x[^}]+)\}", ground_contract.split("actors{{", 1)[1].split("}};", 1)[0])
    assert len(ground_rows) == len(GROUND_PROFILES) == 4
    ground_actors = dict(zip(GROUND_PROFILES, [str(uuid.UUID(bytes_le=bytes(
        int(b.strip(), 16) for b in raw.split(",")))) for raw in ground_rows]))
    lease = (ROOT / "Extension/ArcadeMode/arcade_native_grab_lease.h").read_text()
    profile_rows = re.findall(
        r"\{ArcadeTrick::(\w+),\s*(\d+),\s*(-?[\d.]+)f?,\s*(-?[\d.]+)f?(?:,\s*(\d+),\s*(\d+)(?:,\s*(-?\d+),\s*(-?\d+)(?:,\s*(\d+),\s*(\d+))?)?)?\}", lease)
    contract = (ROOT / "Engine/Game/Build/20260929/arcade_grab_transition.h").read_text()
    # Entry actors share this header but are lifecycle dependencies, not new
    # selectable profiles. Join only the ordered loop/profile array here.
    profile_actors = contract.split("actor_assets{{", 1)[1].split("}};", 1)[0]
    actors = re.findall(r'\{\{(0x[^}]+)\},\s*"([^"]+)"\}', profile_actors)
    assert len(profile_rows) == len(actors) == 57, "profile/actor coverage drift"
    table = (ROOT / "Extension/ArcadeMode/arcade_trick_table.h").read_text()
    labels = dict(re.findall(r'case ArcadeTrick::(\w+): return "([^"]+)";', table))
    labels.update(dict(re.findall(r'TrickTableRow\{[^\n]*ArcadeTrick::(\w+), "([^"]+)"\}', table)))
    profiles = {}
    for row, (raw, name) in zip(profile_rows, actors):
        trick, detail, x, y, family, hands, sx, sy, footer, foot = row
        detail = int(detail)
        footer, foot = int(footer or 0), int(foot or 0)
        guid = str(uuid.UUID(bytes_le=bytes(int(b.strip(), 16) for b in raw.split(","))))
        binding = 'Select "' + labels[trick] + '" in Arcade Mode > R3+B grab; center LS, hold R3 and press B'
        # Direct bindings describe the canonical pose, not an alternate actor sharing its native tag.
        if detail in BINDINGS and "alternate" not in trick:
            binding = BINDINGS[detail] + "; or " + binding
        if footer in FOOT_BINDINGS:
            binding = FOOT_BINDINGS[footer] + "; or " + binding
        profiles[trick] = dict(semantic=trick, native_name=labels[trick], detail=detail, native_actor=guid, actor_name=name,
                              family=int(family or 2), hands=int(hands or 2), tweak=[float(x), float(y)],
                              selector_rs=[int(sx or 0), int(sy or 0)], one_footer=footer, foot_input=foot, arcade_binding=binding)
    detailed = {e["native_id"]: e for e in source["entries"] if e["id_namespace"] == "Enum.DetailedGrabType"}
    footers = {e["native_id"]: e for e in source["entries"] if e["id_namespace"] == "Enum.OneFooterType"}
    for profile in profiles.values():
        identity = footers[profile["one_footer"]] if profile["one_footer"] else detailed[profile["detail"]]
        if profile["one_footer"]:
            seq = next(s for s in source["sequence_inventory"] if s["resource_index"] == FOOT_LOOPS[profile["one_footer"]])
            profile["animation_asset"] = dict(resource_index=seq["resource_index"], name=seq["name"],
                sequence_guid=seq["guid"], actors=[dict(guid=profile["native_actor"])],
                compressed_sha1=seq["sha1"], decoded_sha256=seq["decoded_sha256"])
            continue
        matches = [a for a in identity["animation_assets"]
                   if any(actor["guid"] == profile["native_actor"] for actor in a["actors"])]
        assert len(matches) == 1, "native actor must have exactly one source sequence"
        profile["animation_asset"] = matches[0]
    entries = []
    for entry in source["entries"]:
        ns, value = entry["id_namespace"], entry["native_id"]
        detail = value if ns == "Enum.DetailedGrabType" else GRAB_TO_DETAIL.get(value) if ns == "Enum.GrabType" else None
        footer = value if ns == "Enum.OneFooterType" else GRAB_TO_FOOTER.get(value) if ns == "Enum.GrabType" else None
        variants = [p for p in profiles.values() if (not p["one_footer"] and p["detail"] == detail) or p["one_footer"] == footer]
        seatbelt_declaration = (ns == "Enum.DetailedGrabType" and value == 17) or (ns == "Enum.GrabType" and value == 35)
        if seatbelt_declaration:
            # The source declaration is not the emitted tag. Account for its
            # actual original Seatbelt actor without manufacturing detail17.
            variants = [profiles["seatbelt_bs_shifty"]]
            detail = 24
        row = dict(native_name=entry["native_name"], native_identity={"namespace": ns, "value": value},
                   assets=entry["animation_assets"], native_gameplay_context=entry["context"],
                   original_mechanism=entry["native_transition"], arcade_binding=None,
                   implementation_state=BLOCKED, native_animation_acknowledgment="No RC3 native capture",
                   release_landing_evidence="No RC3 native capture", scoring_evidence="Native numeric scoring unverified",
                   remaining_blocker=blocker(entry), prior_evidence=entry["test_result"])
        if variants:
            row.update(assets=[p["animation_asset"] for p in variants], arcade_binding=[p["arcade_binding"] for p in variants],
                       implementation_state=PENDING if ns in {"Enum.DetailedGrabType", "Enum.OneFooterType"} else DEPENDENT,
                       native_gameplay_context=("Established native airborne grab, then original OneFoot.Into/Loop/Exit in the qualified inspected stance" if footer else
                           "Native airborne Grab.Into/Grab.Loop in the qualified inspected stance; each variant records its original family"),
                       original_mechanism=[{"hand_inputs": p["hands"], "native_family": p["family"],
                                            "detailed_pose": detail, "tweak_xy": p["tweak"], "selector_rs": p["selector_rs"],
                                            "one_footer": p["one_footer"], "foot_input": p["foot_input"],
                                            "ownership": "original native StateFlow and scoring; bounded grab lease"} for p in variants],
                       runtime_actor=[p["native_actor"] for p in variants], executable_variants=variants,
                       native_animation_acknowledgment="Runtime requires exact actor initialization, positive advancement and matching native detail or OneFooterType; tests inject observations only",
                       remaining_blocker="Owner gameplay and full native animation/hold/exit/landing/scoring acceptance outstanding")
            if ns == "Enum.GrabType":
                row["dependency"] = {"namespace": "Enum.OneFooterType" if footer else "Enum.DetailedGrabType", "value": footer or detail}
            if seatbelt_declaration:
                row["implementation_state"] = DEPENDENT
                row["dependency"] = {"namespace": "Enum.DetailedGrabType", "value": 24}
                row["source_identity_note"] = "Original Seatbelt BS Shifty actor emits Nose_BS_Shifty detail24. The unused Seatbelt_BS_Shifty detail17 is not synthesized; native scoring is unchanged."
        if ns == "Enum.GrabType" and value in GROUND_PROFILES:
            binding, resource, name, guid, mechanism = GROUND_PROFILES[value]
            row.update(arcade_binding=[binding], implementation_state=PENDING,
                       runtime_actor=[ground_actors[value]],
                       assets=[dict(resource_index=resource, name=name, sequence_guid=guid)],
                       native_gameplay_context="Ordinary native ground state100; separate input owner; never the airborne grab lease",
                       original_mechanism=mechanism,
                       native_animation_acknowledgment="Runtime requires exact original loop actor initialization and positive advancement in the same owner/context/serial; no native gameplay capture yet",
                       release_landing_evidence="Software verifies release, timeout, owner loss and air withdrawal; native exit/landing still unverified",
                       remaining_blocker="Owner gameplay and exact native animation/exit/scoring acceptance outstanding; airborne Coffin and grab changes while held remain separate blockers")
        finger = fingers.get(value if ns == "Enum.FingerflipType" else GRAB_TO_FINGER.get(value) if ns == "Enum.GrabType" else None)
        if finger:
            row.update(implementation_state=PENDING if ns == "Enum.FingerflipType" else DEPENDENT,
                       runtime_actor=[finger["actor_guid"]],
                       assets=[dict(resource_index=finger["resource"], name=finger["sequence"],
                           sequence_guid=finger["sequence_guid"], actors=[dict(guid=finger["actor_guid"])])],
                       arcade_binding=[finger["arcade_binding"]],
                       native_gameplay_context="Established, acknowledged airborne grab family " + str(finger["family"]) + "; no one-footer or Rocket Air",
                       original_mechanism="Original Input_TrickGesture -> EAT LateFlipBuffer -> Fingerflips action -> CDB entry -> native catch/destination " + str(finger["destination"]),
                       native_animation_acknowledgment="Exact initialized original body actor plus positive advancement and native FingerFlipType required; no gameplay capture yet",
                       release_landing_evidence="Software checks neutral catch, observed destination, release withdrawal, owner loss and timeout; native catch/landing gameplay pending",
                       remaining_blocker="Owner gameplay and native catch, landing and scoring acceptance outstanding")
            if ns == "Enum.GrabType":
                row["dependency"] = dict(namespace="Enum.FingerflipType", value=finger["native_id"])
        entries.append(row)
    seq_rows = []
    for seq in source["sequence_inventory"]:
        links = [dict(namespace=e["id_namespace"], value=e["native_id"])
                 for e in source["entries"] if any(a["resource_index"] == seq["resource_index"] for a in e["animation_assets"])]
        variants = [p for p in profiles.values() if p["animation_asset"]["resource_index"] == seq["resource_index"]]
        row = dict(seq, identity_links=links, implementation_state=BLOCKED,
                   arcade_binding=None, native_animation_acknowledgment="No RC3 capture",
                   release_landing_evidence="No RC3 capture", scoring_evidence="Unverified",
                   remaining_blocker=FINGER_BLOCKER if any(s in seq["name"] for s in ("fingerflip", "varial", "heel_finger")) else
                       FOOT_BLOCKER if any(s in seq["name"] for s in ("onefoot", "1ft", "nofoot", "christ", "judo", "frigid", "airwalk", "benih", "dogpiss", "tailwalk", "superman")) else
                       GROUND_BLOCKER if any(s in seq["name"] for s in ("ground", "coffin")) else ENTRY_BLOCKER)
        if variants:
            assert len(variants) == 1
            row.update(implementation_state=PENDING, arcade_binding=variants[0]["arcade_binding"],
                       remaining_blocker="RC3 native lifecycle and scoring acceptance outstanding")
        finger = next((f for f in finger_rows if f["resource"] == seq["resource_index"]), None)
        if finger:
            row.update(implementation_state=PENDING, arcade_binding=finger["arcade_binding"],
                       identity_links=[dict(namespace="Enum.FingerflipType", value=finger["native_id"])],
                       remaining_blocker="RC3 native animation/catch/landing/scoring acceptance outstanding")
        seq_rows.append(row)
    assert len(entries) == 171 and len(seq_rows) == 300
    observed = json.loads((RESEARCH / "rc3-native-grab-observations.json").read_text())
    footer_entries = {a["one_footer"]: a for a in json.loads(
        (RESEARCH / "native-one-footer-entry-actors.json").read_text())}
    for actor, evidence in observed.items():
        uuid.UUID(actor)
        assert evidence["actor_initialized"] and evidence["positive_advancement"]
        assert re.fullmatch(r"[0-9a-f]{64}", evidence["uncompressed_sha256"])
        assert not evidence["landing_scoring_verified"]
    for entry in entries:
        matches = [observed[a] for a in entry.get("runtime_actor", []) if a in observed]
        # An Into actor proves entry, not advancement of the separate Loop.
        # Keep that distinction when joining hardware receipts to declarations.
        entry_matches = []
        for variant in entry.get("executable_variants", []):
            actor = footer_entries.get(variant["one_footer"])
            if actor and actor["actor"] in observed:
                entry_matches.append(dict(asset=actor, evidence=observed[actor["actor"]]))
        if entry_matches:
            entry["rc3_native_entry_evidence"] = entry_matches
            entry["native_animation_acknowledgment"] = (
                "Exact original Into actor initialized and advanced; separate Loop, exit and scoring remain unverified. "
                "See rc3_native_entry_evidence, including failed lifecycle observations.")
        if matches:
            entry.update(rc3_native_evidence=matches,
                         native_animation_acknowledgment="Exact original actor initialized and advanced; see each receipt's source SHA in rc3_native_evidence. This does not establish every variant in this row.",
                         release_landing_evidence="SDK input-request withdrawal is recorded where present; this does not by itself prove native intent clearance. Exact native exit actor and numeric landing/combo scoring remain unverified; consult each receipt for its gameplay context and lifecycle limits.",
                         remaining_blocker="Remaining variants, changed-stance behavior, complete hold/exit/landing/scoring and owner visual acceptance remain pending.")
    # A known failed lifecycle is a blocker, not merely an outstanding owner
    # confirmation. Preserve entry evidence and reachable bindings alongside it.
    failures = json.loads((RESEARCH / "rc3-native-grab-lifecycle-failures.json").read_text())["one_footers"]
    assert len({f["native_id"] for f in failures}) == len(failures)
    for failure in failures:
        footer = failure["native_id"]
        assert footer in FOOT_LOOPS and re.fullmatch(r"[0-9a-f]{64}", failure["capture_sha256"])
        for row in entries:
            identity = row["native_identity"]
            value = identity["value"]
            matches = (identity["namespace"] == "Enum.OneFooterType" and value == footer) or (
                identity["namespace"] == "Enum.GrabType" and GRAB_TO_FOOTER.get(value) == footer)
            if matches:
                if identity["namespace"] == "Enum.OneFooterType":
                    row["implementation_state"] = BLOCKED
                row.update(native_lifecycle_failure=failure,
                           release_landing_evidence=failure["observation"], remaining_blocker=failure["blocker"])
        for row in seq_rows:
            if row["resource_index"] == FOOT_LOOPS[footer]:
                row.update(implementation_state=BLOCKED, native_lifecycle_failure=failure,
                           release_landing_evidence=failure["observation"], remaining_blocker=failure["blocker"])
    return dict(schema_version=7, rc2_source="2ffb006c73671466bfcdc15395ba96939de44f7d",
                accounting_complete_for_input_inventory=True, native_catalog_exhaustiveness_proven=False,
                feature_complete=False, game_exe_sha256=source["game_exe_sha256"],
                scope=source["scope"], independently_mapped_native_poses=len(profiles),
                independently_mapped_detailed_identities=len({p["detail"] for p in profiles.values() if not p["one_footer"]}),
                independently_mapped_one_footer_identities=len({p["one_footer"] for p in profiles.values() if p["one_footer"]}),
                independently_mapped_ground_identities=len(GROUND_PROFILES),
                independently_mapped_fingerflip_identities=len(fingers),
                mapped_fingerflip_transitions=finger_rows,
                mapped_profiles=list(profiles.values()),
                native_actor_evidence_count=len(observed),
                counts=dict(declarations=dict(Counter(e["implementation_state"] for e in entries)),
                            sequences=dict(Counter(e["implementation_state"] for e in seq_rows))),
                caveats=["Namespace counts overlap; never add them as a unique playable-trick count.",
                         "All 171 declarations and all 300 sequences are accounted for; unresolved assets are BLOCKED, never inferred UNSUPPORTED.",
                         "Source catalog itself does not prove exhaustive discovery of every original executable context.",
                         "Per-actor initialization/advancement receipts identify their exact source. Into evidence does not prove the separate Loop; no complete lifecycle or numeric scoring acceptance is claimed.",
                         "Indy slot resolves to native FS. Madonna, One Foot Japan and Sacktap remain unresolved catalog names; no substitute actor is assigned."],
                source_anomalies=source["source_anomalies"], entries=entries, sequence_inventory=seq_rows)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = build()
    rendered = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    if args.check:
        assert OUTPUT.read_text() == rendered, "regenerate rc3-grab-coverage.json"
    else:
        OUTPUT.write_text(rendered)
    print(json.dumps(data["counts"]))
