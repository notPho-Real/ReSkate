int main() {
    unsigned checks{};
    for (const auto& test : cases) {
        UnifiedInput input; Sink sink; const InputAdapter adapter{&sink,&Sink::receive};
        InputEnvironment env{InputContext::balance,true}; env.policy=InputPolicy::strict();
        env.balance_branch=test.context; env.branch_ready=false;
        input.poll(0,{},env,adapter);
        if (test.kind == 0) {
            input.poll(10,{static_cast<std::uint16_t>(1u << static_cast<unsigned>(test.first))},env,adapter);
            input.poll(20,{},env,adapter);
            input.poll(30,{static_cast<std::uint16_t>(1u << static_cast<unsigned>(test.second))},env,adapter);
        } else if (test.kind == 1) {
            input.poll(10,{0,0,0, static_cast<std::uint8_t>(test.first == 0 ? 255 : 0),
                static_cast<std::uint8_t>(test.first == 1 ? 255 : 0)},env,adapter);
        } else {
            input.poll(10,direction(test.first),env,adapter); input.poll(20,{},env,adapter);
            input.poll(30,direction(test.second),env,adapter); input.poll(40,{0x4000},env,adapter);
        }
        if(sink.calls) { std::cerr << "premature branch while initialization is unavailable\n"; return 1; }
        env.branch_ready=true;
        input.poll(10+test.age,{},env,adapter);
        ++checks;
        if ((test.target != 255 && (sink.calls != 1 || sink.last.variant != test.target)) ||
            (test.target == 255 && sink.calls != 0) || input.diagnostic().unresolved_definition != test.unresolved) {
            std::cerr << "graph mismatch context=" << test.context << " kind=" << test.kind << " first=" << test.first << " second=" << test.second
                << " age=" << test.age << " expected=" << test.target << " actual=" << (sink.calls ? static_cast<unsigned>(sink.last.variant) : 255u) << '\n'; return 1;
        }
        if(env.balance_branch != test.context) return 1;
    }
    std::cout << checks << " independently specified branch graph cases passed\n";
}

