"""The shared fixture writer must have one owner before either compiler runs."""
from pathlib import Path
import re
import unittest


def validate(source):
    source = re.sub(r'#[^\n]*', '', source)
    commands = re.findall(r'(\w+)\(([^()]*)\)', source, re.S)
    by_name = lambda name: [body.split() for kind, body in commands if kind == name]
    generators = [args for args in by_name('add_custom_command') if '"${CMAKE_CURRENT_SOURCE_DIR}/generate.py"' in args]
    if len(generators) != 1:
        raise ValueError('exactly one fixture generation command required')
    args = generators[0]
    if args[:2] != ['OUTPUT', '"${capture_generation_stamp}"'] or 'BYPRODUCTS' not in args:
        raise ValueError('stamp must own both generated byproducts')
    for output in ('"${capture_generated}"', '"${capture_teardown_generated}"'):
        if output not in args[args.index('BYPRODUCTS') + 1:args.index('COMMAND')]:
            raise ValueError('missing generated byproduct')
    if ['dingosdk_arcade_capture_schema4_generate', 'DEPENDS', '"${capture_generation_stamp}"'] not in by_name('add_custom_target'):
        raise ValueError('single owning generation target required')
    for target in ('dingosdk_arcade_capture_schema4_emitter_tests', 'dingosdk_arcade_capture_schema4_teardown_tests'):
        if [target, 'dingosdk_arcade_capture_schema4_generate'] not in by_name('add_dependencies'):
            raise ValueError('compiler must depend on completed shared generation')
    if args.count('"${capture_generation_stamp}"') != 2:
        raise ValueError('stamp must be touched after successful generation')


class DependencyTests(unittest.TestCase):
    def test_current_graph(self):
        validate(Path(__file__).with_name('CMakeLists.txt').read_text())

    def test_missing_owner_edges_rejected(self):
        source = Path(__file__).with_name('CMakeLists.txt').read_text()
        for target in ('dingosdk_arcade_capture_schema4_emitter_tests', 'dingosdk_arcade_capture_schema4_teardown_tests'):
            with self.assertRaisesRegex(ValueError, 'compiler must depend'):
                validate(source.replace('add_dependencies(' + target + ' dingosdk_arcade_capture_schema4_generate)', ''))

    def test_direct_multioutput_regression_rejected(self):
        source = Path(__file__).with_name('CMakeLists.txt').read_text()
        with self.assertRaisesRegex(ValueError, 'stamp must own'):
            validate(source.replace('OUTPUT "${capture_generation_stamp}"\n    BYPRODUCTS', 'OUTPUT'))

    def test_owning_target_missing_rejected(self):
        source = Path(__file__).with_name('CMakeLists.txt').read_text()
        with self.assertRaisesRegex(ValueError, 'single owning'):
            validate(source.replace('add_custom_target(dingosdk_arcade_capture_schema4_generate DEPENDS "${capture_generation_stamp}")', ''))


if __name__ == '__main__':
    unittest.main()
